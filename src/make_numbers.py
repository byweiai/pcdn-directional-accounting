"""Emit paper/numbers.tex: every number the manuscript prints, as a macro.

Rule: the body never types a digit that came out of an experiment.  It calls
\\eOneClientMed{} etc., and this script is the only place that reads the JSON.
Re-run after any experiment change.

Usage:  py -3.13 src\\make_numbers.py
"""
import io
import json
import numpy as np
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'data')
OUT = os.path.join(ROOT, 'paper', 'numbers.tex')


def load(name):
    return json.load(io.open(os.path.join(DATA, name + '.json'), encoding='utf-8'))


def f(x, nd=4):
    return ('%.' + str(nd) + 'f') % x


def pct(x, nd=1):
    return ('%.' + str(nd) + 'f') % (100.0 * x)


def si(x):
    return '{:,}'.format(int(round(x)))


def main():
    L = ['% generated by src/make_numbers.py -- do not edit', '']
    m = {}

    # ---------------- E1: endpoint accounting on UNSW-NB15 ----------------
    e1 = load('e1_unsw')
    rs, ps = e1['role_stats'], e1['panel_role_stats']
    m['eOneFlows'] = si(e1['n_flows'])
    m['eOneEndpoints'] = str(e1['n_endpoints_ge5'])
    m['eOneClientMed'] = f(rs['client']['median'])
    m['eOneServiceMed'] = f(rs['service']['median'])
    m['eOneSepP'] = f(e1['auc_service_vs_client'], 3)
    m['eOneFlowMed'] = f(e1['flow_rho_percentiles']['p50'], 3)
    m['eOneAmbPct'] = pct(e1['flow_rho_ambiguous_share'])
    m['eOnePanelCell'] = si(e1['panel_cells'])
    m['eOnePanelCliMed'] = f(ps['client']['median'])
    m['eOnePanelCliPninety'] = f(ps['client']['p90'])
    m['eOnePanelSvcMed'] = f(ps['service']['median'])
    m['eOnePanelSvcPten'] = f(ps['service']['p10'])
    m['eOnePanelCliN'] = si(ps['client']['n'])
    m['eOnePanelSvcN'] = si(ps['service']['n'])

    # ---------------- E2: evasion window on mutable features --------------
    e2 = load('e2_window')
    sw = {round(r['alpha'], 3): r for r in e2['sweep']}
    m['eTwoLo'] = f(min(e2['evasion_window']), 2)
    m['eTwoHi'] = f(max(e2['evasion_window']), 2)
    m['eTwoLoPct'] = f(100.0 * min(e2['evasion_window']), 0)
    m['eTwoHiPct'] = f(100.0 * max(e2['evasion_window']), 0)
    m['eTwoN'] = str(len(e2['evasion_window']))
    m['eTwoCleanAuc'] = f(e2['detector_auc_clean'])
    m['eTwoTprHi'] = pct(sw[0.40]['tpr'])
    m['eTwoRhoHi'] = f(sw[0.40]['rho'])
    m['eTwoTprLo'] = pct(sw[0.05]['tpr'])
    m['eTwoRhoLo'] = f(sw[0.05]['rho'])
    m['eTwoAtQuotaTpr'] = pct(sw[0.50]['tpr'])
    m['eTwoAtQuotaRho'] = f(sw[0.50]['rho'])
    def tre(v, nd=1):
        """One decimal, trailing zeros trimmed: 19.2459 -> 19.2, 24.0184 -> 24."""
        return ('%.*f' % (nd, v)).rstrip('0').rstrip('.')
    m['eTwoXForRho'] = tre(sw[0.04]['volume_up_x'])
    m['eTwoXAtLo'] = tre(sw[0.40]['volume_up_x'])
    m['eTwoXForty'] = tre(sw[0.40]['volume_up_x'])
    m['eTwoXFive'] = tre(sw[0.05]['volume_up_x'])
    m['eTwoCarryXHiding'] = tre(sw[0.04]['volume_up_x'])
    m['eTwoDownX'] = f(sw[0.05]['downlink_x'], 1)
    m['eTwoDownXHiding'] = f(sw[0.04]['downlink_x'], 1)
    m['eTwoXTen'] = tre(sw[0.10]['volume_up_x'])
    m['eTwoDownXTen'] = tre(sw[0.10]['downlink_x'])
    m['eTwoRhoAtHiding'] = f(sw[0.04]['rho'])
    m['eTwoPninety'] = f(e2['client_rho_p90'])
    m['eTwoNfeat'] = str(len(e2['features']))
    # held-out scoring, capped per address pair (X01/C10)
    sp = e2['sweep_split']
    ho = e2['heldout']
    hn = e2['heldout_noport']
    m['eTwoCap'] = str(50)
    m['eTwoPairs'] = si(sp['pairs'])
    m['eTwoHeldoutTpr'] = pct(ho['tpr'])
    m['eTwoHeldoutFpr'] = f(100.0 * ho['fpr'], 2)
    m['eTwoHeldoutNoPort'] = pct(hn['tpr'])
    m['eTwoHeldoutFprNoPort'] = f(100.0 * hn['fpr'], 2)
    # the aggregate rule empties while the class-conditional rule does not
    m['eTwoDist'] = pct(sw[0.60]['dist_flag_rate'])
    m['eTwoDistLo'] = pct(sw[0.05]['dist_flag_rate'])
    m['eTwoCons'] = f(100.0 * float(np.mean([r['cons_flag_rate'] for r in
                                             e2['sweep'] if r['cons_flag_rate'] == r['cons_flag_rate']])), 2)
    m['eTwoTprAtOne'] = pct(sw[1.0]['tpr'])
    m['eTwoRatioHi'] = pct(sw[1.0]['ratio_rule_rate'])
    m['eTwoRatioLo'] = pct(sw[0.05]['ratio_rule_rate'])
    dg = {round(r['delta'], 3): r for r in e2['disguise']}
    m['eTwoDisguiseOne'] = f(100.0 * dg[1.0]['flag_disguised'], 2)
    m['eTwoDisguiseQOne'] = pct(dg[0.25]['flag_all'])
    m['eTwoDisguiseQTwo'] = pct(dg[0.5]['flag_all'])
    m['eTwoDisguiseQThree'] = pct(dg[0.75]['flag_all'])

    # ---------------- E3: external shape, extrapolation, persistence ------
    e3 = load('e3_external')
    c = e3['cic']
    m['eThreeCicFlows'] = si(c['n_flows'])
    m['eThreeCicEndpoints'] = si(c['n_endpoints'])
    m['eThreeCicLow'] = f(c['peaks'][3], 3)
    m['eThreeCicLow2'] = f(c['peaks'][2], 3)
    m['eThreeCicHigh'] = f(c['peaks'][1], 3)
    m['eThreeCicPeak'] = f(c['peaks'][0], 3)
    m['eThreeCicValley'] = f(c['valley_rho'], 3)
    m['eThreeCicValleyPct'] = pct(c['valley_over_peak'], 0)
    m['eThreeCicMedian'] = f(c['rho_median'], 3)
    m['eThreeQuota'] = f(e3['time']['quota'])
    m['eThreePeriods'] = str(len(e3['time']['hours']) - 1)
    fp = [h['false_positive'] for h in e3['time']['hours']]
    cap = [h['capture'] for h in e3['time']['hours']]
    m['eThreeFpMax'] = f(max(fp))
    m['eThreeCapMin'] = f(min(cap))
    m['eThreeCapMax'] = f(max(cap))
    a = e3['attack']
    m['eThreeWin'] = str(a['window_seconds'] // 60) + '\\,min'
    m['eThreeNwin'] = si(a['n_windows_total'])
    m['eThreeSvcRun'] = f(a['by_role']['service']['longest_run_median'], 1)
    m['eThreeSvcShare'] = f(a['by_role']['service']['over_share_median'], 2)
    m['eThreeCliRun'] = f(a['by_role']['client']['longest_run_median'], 1)
    m['eThreeCrossers'] = str(a['crossers']['n'])
    m['eThreeCrosserSvc'] = pct(a['crossers']['service_share'], 0)
    m['eThreePersist'] = str(a['crossers']['persistent_90pct'])
    m['eThreePersistSvc'] = str(a['crossers']['persistent_90pct_service'])
    m['eThreePersistAtk'] = str(a['crossers']['persistent_90pct_attacker'])
    m['eThreeAtkShare'] = f(a['crossers']['attacker_over_share_median'], 2)

    # ---------------- E4: declared ratios across 35,849 networks ----------
    e4 = load('e4_peeringdb')
    m['eFourNets'] = si(e4['n_networks'])
    m['eFourDeclared'] = pct(e4['declared_share'])
    m['eFourInMinusOut'] = si(e4['inbound_minus_outbound'])
    m['eFourCramer'] = f(e4['cramers_v'])
    kinds, labels, T = e4['kinds'], e4['ratio_labels'], e4['table']
    ki = {k: i for i, k in enumerate(kinds)}
    li = {k: i for i, k in enumerate(labels)}

    def row_share(kind, labs):
        r = T[ki[kind]]
        tot = sum(r)
        return 100.0 * sum(r[li[x]] for x in labs) / tot

    m['eFourAccessIn'] = pct(row_share('Cable/DSL/ISP',
                                       ['Heavy Inbound', 'Mostly Inbound']) / 100.0, 1)
    m['eFourAccessN'] = si(sum(T[ki['Cable/DSL/ISP']]))
    m['eFourContentOut'] = pct(row_share('Content',
                                         ['Mostly Outbound', 'Heavy Outbound']) / 100.0, 1)
    m['eFourContentN'] = si(sum(T[ki['Content']]))
    m['eFourNspBal'] = pct(row_share('NSP', ['Balanced']) / 100.0, 1)
    m['eFourNspN'] = si(sum(T[ki['NSP']]))
    m['eFourUnknownDisc'] = pct(row_share('Unknown', ['Not Disclosed']) / 100.0, 1)

    # ---------------- E5: three regimes ----------------------------------
    e5 = load('e5_regime')
    b = e5['base']
    m['eFiveSpot'] = f(b['p_spot'], 2)
    m['eFiveRate'] = f(b['p_provider'], 2)
    m['eFiveTrippedBase'] = pct(b['tripped_share_of_base'], 2)
    m['eFiveTrippedProv'] = pct(b['tripped_share_of_providers'], 1)
    m['eFiveReg'] = pct(b['registration_rate'])
    m['eFiveDisclosed'] = pct(b['disclosed_volume_share'])
    for s in ('S1', 'S2', 'S3'):
        n = {'S1': 'One', 'S2': 'Two', 'S3': 'Three'}[s]
        m['eFiveWelfare' + n] = si(b['welfare'][s])
        m['eFiveMargin' + n] = si(b['operator_margin'][s])
        m['eFiveHarm' + n] = si(b['unpriced_harm'][s])
        m['eFiveVol' + n] = si(b['volume_served'][s])
        m['eFiveHarmGb' + n] = f(b['harm_per_gb_served'][s], 3)
        m['eFiveProfit' + n] = si(b['provider_profit'][s])
    m['eFiveWelfareRatio'] = f(b['welfare']['S3'] / b['welfare']['S1'], 1)
    m['eFiveHarmRatio'] = f(b['harm_per_gb_served']['S1'] / b['harm_per_gb_served']['S3'], 1)
    m['eFiveCliFreePct'] = pct(1.0 - b['tripped_share_of_base'], 1)

    pr = e5['provider_rate']
    p_star = e5['params']['E_UPLINK'] + e5['params']['LAMBDA_CAP']
    m['eFiveBestMarginRate'] = f(max(pr, key=lambda r: r['operator_margin_S3'])['p_provider'], 2)
    m['eFiveBestMargin'] = si(max(r['operator_margin_S3'] for r in pr))
    m['eFiveRateStar'] = f(p_star, 2)
    at_star = [r for r in pr if abs(r['p_provider'] - p_star) < 1e-9][0]
    m['eFiveRegAtStar'] = pct(at_star['registration_rate'])
    m['eFiveWelfareAtStar'] = si(at_star['welfare_S3'])
    zero = [r for r in pr if r['operator_margin_S3'] >= -1.0][0]
    m['eFiveFirstSolvent'] = f(zero['p_provider'], 2)
    m['eFiveWelfareLossPct'] = f(100.0 * (at_star['welfare_S3']
                                          - max(pr, key=lambda r: r['operator_margin_S3'])['welfare_S3'])
                                 / at_star['welfare_S3'], 1)

    ev = e5['evasion']
    hi = [r for r in ev if not r['laundering_pays']]
    lo = [r for r in ev if r['laundering_pays']]
    m['eFiveEvasionSwitch'] = f(max(r['evasion_cost'] for r in lo), 2)
    m['eFiveS2MarginHigh'] = si(max(r['operator_margin_S2'] for r in ev))
    m['eFiveS2MarginLow'] = si(min(r['operator_margin_S2'] for r in ev))
    m['eFiveS3MarginFlat'] = si({round(r['operator_margin_S3'], 3) for r in ev}.pop())

    # ---------------- E7: meter cost -------------------------------------
    e7 = load('e7_meter')['summary']
    m['eSevenExact'] = f(e7['records_per_sec_exact'] / 1e6, 2)
    m['eSevenCms'] = f(e7['records_per_sec_cms'] / 1e6, 2)
    m['eSevenSs'] = f(e7['records_per_sec_ss'] / 1e6, 2)
    m['eSevenCmsErr'] = pct(e7['cms_rel_err_mean'], 2)
    m['eSevenCmsMem'] = f(e7['cms_memory_kib'], 0)
    m['eSevenSsMem'] = f(e7['ss_memory_kib'], 0)
    m['eSevenExactMem'] = f(16.0 * e7['exact_counters_max'] / 1024.0, 0)
    m['eSevenExactCounters'] = si(e7['exact_counters_max'])
    m['eSevenStateKib'] = f(16.0 * 20000 / 1024.0, 0)
    m['eSevenMeanPkt'] = f(e7['mean_packet_bytes'], 1)
    m['eSevenGbps'] = f(e7['records_per_sec_exact'] * e7['mean_packet_bytes'] * 8.0 / 1e9, 1)
    m['eSevenPortRatio'] = f(e7['records_per_sec_exact'] * e7['mean_packet_bytes'] * 8.0 / 1e10, 2)
    m['eSevenMpps'] = f(1e10 / 8.0 / 1000.0 / 1e6, 2)
    # what a ten-gigabit port demands at this benchmark's own mean packet size,
    # and how far each structure sits above or below that demand
    demand = 1e10 / 8.0 / e7['mean_packet_bytes']
    m['eSevenCmsShort'] = f(demand / e7['records_per_sec_cms'], 1)
    m['eSevenSsShort'] = f(demand / e7['records_per_sec_ss'], 0)

    # ---------------- E8: aggregation window -----------------------------
    e8 = {r['window_s']: r for r in load('e8_window')['rows']}
    r3 = e8[300]
    m['eEightWin'] = '300'
    m['eEightCells'] = si(r3['cells'])
    m['eEightFp'] = f(r3['fp_cell'])
    m['eEightTpr'] = f(r3['tpr_cell'])
    m['eEightTprS3'] = f(r3['tpr_sustained3'])
    m['eEightFpS3'] = f(r3['fp_sustained3'])
    m['eEightAuc'] = f(r3['auc'])
    m['eEightCliP95'] = f(r3['client_p95'])
    m['eEightSvcP05'] = f(r3['service_p05'])
    m['eEightCliMed'] = f(r3['client_p50'])
    m['eEightSvcMed'] = f(r3['service_p50'])
    m['eEightMinFp'] = f(max(r['fp_cell'] for r in e8.values()))
    m['eEightShortWin'] = '60'
    m['eEightShortFp'] = f(e8[60]['fp_cell'])
    m['eEightLongTpr'] = f(e8[1800]['tpr_sustained3'])

    # ---------------- E9: threshold scan ---------------------------------
    e9 = load('e9_threshold')
    sc = {round(r['tau'], 2): r for r in e9['scan']}
    m['eNineTau'] = f(0.25, 2)
    m['eNineFpAtTau'] = f(sc[0.25]['false_alarm'])
    m['eNineCapAtTau'] = f(sc[0.25]['capture'], 3)
    m['eNineQuotaAtTau'] = f(sc[0.25]['quota'], 2)
    m['eNineFpAtHalf'] = f(sc[0.50]['false_alarm'])
    m['eNineCapAtHalf'] = f(sc[0.50]['capture'], 3)
    m['eNineFpAtTen'] = f(sc[0.10]['false_alarm'], 3)
    m['eNineCapAtTen'] = f(sc[0.10]['capture'], 3)
    m['eNineCapGain'] = f(100.0 * (sc[0.25]['capture'] - sc[0.50]['capture']), 1)
    m['eNineQuotaAtHalf'] = f(sc[0.50]['quota'], 2)
    m['eNineFpAtFifteen'] = f(sc[0.15]['false_alarm'], 3)
    m['eNineCapAtFifteen'] = f(sc[0.15]['capture'], 3)
    m['eNineFpAtTwenty'] = f(sc[0.20]['false_alarm'], 3)
    m['eNineCapAtTwenty'] = f(sc[0.20]['capture'], 3)

    # --- E10: the temporal closure (SIEVE)
    e10 = load('e10_temporal')
    sc = e10['schedules']
    m['eTenWindow'] = f(e10['window_s'], 0)
    m['eTenHorizon'] = f(e10['horizon'], 0)
    m['eTenMinRun'] = f(e10['min_interval'], 0)
    m['eTenSenders'] = f(sc['steady']['n'], 0)
    m['eTenSubs'] = f(e10['subscriber']['n'], 0)
    m['eTenFloor'] = f(e10['sieve']['budget_mb'], 0)
    m['eTenSlope'] = f(e10['sieve']['rate_mb_per_window'], 1)
    for nm in ('steady', 'alternate', 'pulse', 'ramp'):
        cap = nm.capitalize()
        m['eTenRule' + cap] = f(sc[nm]['rule3_rate'], 3)
        m['eTenIv' + cap] = f(sc[nm]['interval_ratio_rate'], 3)
        m['eTenSieve' + cap] = f(sc[nm]['sieve_rate'], 3)
        m['eTenRuleExp' + cap] = f(sc[nm]['rule3_median_exposure'], 1)
        m['eTenIvExp' + cap] = f(sc[nm]['interval_ratio_median_exposure'], 1)
        m['eTenSieveExp' + cap] = f(sc[nm]['sieve_median_exposure'], 1)
    sub = e10['subscriber']
    m['eTenSubFpRun'] = f(sub['rule3_false_alarm'], 3)
    m['eTenSubFpIv'] = f(sub['interval_ratio_false_alarm'], 3)
    m['eTenSubFpSieve'] = f(sub['sieve_false_alarm'], 3)
    m['eTenSubMargin'] = f(sub['worst_excess_over_rate_mb'], 2)
    # the subgroup the floor removes: endpoints undetected under the steady replay
    und = [v['steady'] for v in e10['endpoints'].values() if v['steady']['sieve'] is None]
    exc = [u['m_s_mb'] - u['m_r_mb'] for u in und]
    pos = [x for x in exc if x > 0]
    m['eTwelveUndetN'] = f(len(und), 0)
    m['eTwelveUndetPos'] = f(len(pos), 0)
    m['eTwelveUndetLo'] = f(min(pos), 2) if pos else '0.00'
    m['eTwelveUndetHi'] = f(max(pos), 2) if pos else '0.00'

    # --- E11: the granularity closure (TRIBUTARY, CONFLUENCE)
    e11 = load('e11_farm')
    m['eElevenLines'] = f(e11['subscriber_lines'], 0)
    m['eElevenConsMed'] = si(e11['consumption_median_mb'])
    m['eElevenUpMed'] = f(e11['uplink_median_mb'], 1)
    law = {(round(r['tau'], 2), round(r['volume_x_household'], 1)): r
           for r in e11['law']}
    m['eElevenLawTauHigh'] = f(0.50, 2)
    m['eElevenLawTauLow'] = f(0.25, 2)
    m['eElevenKLawHigh'] = f(law[(0.50, 10.0)]['k_law'], 0)
    m['eElevenKReplayHigh'] = f(law[(0.50, 10.0)]['k_replay'], 0)
    m['eElevenKLawLow'] = f(law[(0.25, 10.0)]['k_law'], 0)
    m['eElevenKReplayLow'] = f(law[(0.25, 10.0)]['k_replay'], 0)
    m['eElevenKUnitHigh'] = f(law[(0.50, 1.0)]['k_law'], 0)
    m['eElevenKUnitLow'] = f(law[(0.25, 1.0)]['k_law'], 0)
    for r in e11['replay']:
        tag = 'High' if abs(r['tau'] - 0.50) < 1e-9 else 'Low'
        m['eElevenGroup' + tag] = f(r['group_rho'], 3)
        m['eElevenPerLine' + tag] = f(r['line_rho_best_case'], 3)
    cf = e11['confluence']
    m['eElevenSimLines'] = f(cf['lines'], 0)
    m['eElevenSplit'] = f(cf['split_lines'], 0)
    m['eElevenAudience'] = f(cf['audience'], 0)
    best = [r for r in cf['scan'] if abs(r['threshold'] - 0.25) < 1e-9][0]
    loose = [r for r in cf['scan'] if abs(r['threshold'] - 0.10) < 1e-9][0]
    tight = [r for r in cf['scan'] if abs(r['threshold'] - 0.40) < 1e-9][0]
    perfect = [r['threshold'] for r in cf['scan']
               if r['recall'] == 1.0 and r['precision'] == 1.0]
    m['eElevenRecallBest'] = f(best['recall'], 2)
    m['eElevenPrecBest'] = f(best['precision'], 2)
    m['eElevenCompBest'] = f(best['component'], 0)
    m['eElevenThrBest'] = f(best['threshold'], 2)
    m['eElevenCompLoose'] = f(loose['component'], 0)
    m['eElevenThrLoose'] = f(loose['threshold'], 2)
    m['eElevenCompTight'] = f(tight['component'], 0)
    m['eElevenThrTight'] = f(tight['threshold'], 2)
    m['eElevenRecallTight'] = f(tight['recall'], 2)
    m['eElevenThrLo'] = f(min(perfect), 2)
    m['eElevenThrHi'] = f(max(perfect), 2)
    m['eElevenShared'] = f(cf['shared_per_line'], 0)

    # ---- E12: the SIEVE floor is one parameter, not two
    e12 = load('e12_floor')
    fl = {round(r['floor'], 2): r for r in e12['floors']}
    m['eTwelveSubMaxExcess'] = f(e12['subscriber_max_excess'], 2)
    m['eTwelveSvcMedExcess'] = f(e12['roles']['service']['median'], 1)
    m['eTwelveSvcNinetyExcess'] = f(e12['roles']['service']['p90'], 1)
    m['eTwelveSvcMaxExcess'] = f(e12['roles']['service']['max'], 1)
    m['eTwelveCapAtZero'] = f(fl[0.0]['service'], 3)
    m['eTwelveCapAtOne'] = f(fl[1.0]['service'], 3)
    m['eTwelveCapAtFive'] = f(fl[5.0]['service'], 3)
    m['eTwelveFpAtFloor'] = f(fl[5.0]['client'], 3)
    cs = e12['collapse']
    by = {(round(c['B']), c['L']): c for c in cs}
    m['eTwelveEStar'] = f(by[(10, 24)]['e_star'], 2)
    m['eTwelveEStarShort'] = f(by[(10, 12)]['e_star'], 2)
    m['eTwelveEStarLong'] = f(by[(10, 48)]['e_star'], 2)
    m['eTwelveEStarNoB'] = f(by[(0, 24)]['e_star'], 2)
    m['eTwelveEStarBigB'] = f(by[(100, 24)]['e_star'], 2)

    # ---- constants that the prose quotes as parameters rather than results
    e5b = load('e5_regime')
    m['eFiveDetTpr'] = f(e5b['params']['DET_TPR'], 2)
    m['eFiveTriggerFloor'] = f(e5b['params']['UP_TRIGGER_X'] * e5b['params']['HOUSE_UP_GB'], 0)
    m['eFiveUpFactor'] = tre(e5b['params']['UP_TRIGGER_X'])
    m['eFiveHouseUp'] = f(e5b['params']['HOUSE_UP_GB'], 0)
    m['eFiveHouseDn'] = f(e5b['params']['HOUSE_DN_GB'], 0)
    # X06: the volume-only trigger at the same floor and ceiling
    vt = e5b['volume_trigger']
    m['eFiveRatioAsked'] = si(vt['ratio_trigger']['lines_asked'])
    m['eFiveVolAsked'] = si(vt['volume_trigger']['lines_asked'])
    m['eFiveAskedExtra'] = si(vt['lines_asked_extra'])
    m['eFiveVolHouse'] = f(vt['households_asked_extra'], 0)
    m['eFiveHouseTotal'] = si(e5b['params']['HOUSE_N'])
    m['eFiveDeclareBreakeven'] = si(e5['params']['CONSUMER_UPLINK_CAP_GB'] * (e5['params']['P_MARKET'] - e5['params']['C_NODE_MARGIN'])
                                 / (e5['params']['P_MARKET'] - e5['params']['C_NODE_MARGIN'] - e5['params']['P_PROVIDER']))
    m['eFiveVolHousePct'] = f(100.0 * vt['households_asked_extra'] / e5b['params']['HOUSE_N'], 2)
    e8b = load('e8_window')
    m['eEightTprOneMin'] = f(e8b['rows'][0]['tpr_cell'], 3)
