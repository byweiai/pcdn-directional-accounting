    m['eEighteenAbove'] = f(max(r['sieve'] for g in big for r in g
                                if r['wash'] >= 1.0), 3)
    m['eEighteenEscape'] = f(min(r['wash'] for g in big for r in g
                                 if r['sieve'] < 0.5), 2)
    m['eEighteenSmallEscape'] = f(sorted({r['wash'] for r in g18['1']
                                          if r['sieve'] < 0.5})[0], 2)
    m['eEighteenLargest'] = f(e18['params']['M_GRID'][-1], 0)

    # ---------------- R1/R4: what the welfare figure is made of -----------
    # S3 welfare is 0.23 CNY/GB times a volume. With no demand slope the ratio
    # to the flat-rate regime equals the traffic ratio exactly, because both
    # regimes sell the same amount: the headline multiple is a volume ratio.
    dem = {r['eps']: r for r in e5['demand']}
    for tag, key in (('NoEps', None), ('EpsHalf', 0.5), ('EpsOne', 1.0)):
        r = dem.get(key)
        if r is None:
            continue
        m['welfRatio' + tag] = f(r['ratio'], 2)
        m['welfTransfer' + tag] = f(r['transfer_ratio'], 2)
        m['welfCs' + tag] = si(r['consumer_surplus']['S3'])
        m['welfShare' + tag] = f(100.0 * r['gain_share'], 1)
        m['welfCsShare' + tag] = f(100.0 * r['cs_gain_share'], 1)
    if None in dem:
        m['welfVolumeRatio'] = f(dem[None]['volume_ratio'], 2)
    qr = e5.get('quota_rule', [])
    rb = [r for r in qr if r['rule'] == 'billed']
    rr = [r for r in qr if r['rule'] == 'ratio']
    if rb:
        m['quotaBilledLow'] = si(rb[0]['operator_margin_S2'])
        m['quotaBilledMid'] = si(rb[3]['operator_margin_S2'])
        m['quotaBilledHigh'] = si(rb[-1]['operator_margin_S2'])
        m['quotaSpotLow'] = f(rb[0]['p_spot'], 2)
        m['quotaSpotHigh'] = f(rb[-1]['p_spot'], 2)
    if rr:
        m['quotaRatioMid'] = si(rr[3]['operator_margin_S2'])
        m['quotaRatioFail'] = f(min(r['p_spot'] for r in rr if r['laundering_pays']), 2)
    w = e5.get('wash', {})
    if w:
        m['washCrossover'] = f(w['crossover_gb'], 1)
        m['washMultiple'] = f(w['crossover_over_floor'], 2)
        m['washShareAbove'] = pct(w['share_above_crossover'])
        m['washShareBelow'] = f(100.0 * (1.0 - w['share_above_crossover']), 1)
        m['washDeclare'] = f(w['per_gb_declare'], 3)
        m['washPrice'] = f(w['per_gb_wash'], 3)
