    bad = [k for k in m if any(c.isdigit() for c in k)]
    assert not bad, bad

    for k, v in m.items():
        L.append('\\newcommand{\\%s}{%s}' % (k, v))
    io.open(OUT, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print('wrote %s (%d macros)' % (OUT, len(m)))


